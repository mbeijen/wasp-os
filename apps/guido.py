    def foreground(self):
        """Activate the application."""
        self._page = 0
        self._draw()
        wasp.system.request_event(wasp.EventMask.TOUCH |
                                  wasp.EventMask.SWIPE_LEFTRIGHT |
                                  wasp.EventMask.SWIPE_UPDOWN)

    def touch(self, event):
        """Show the next picture."""
        self._next()

    def swipe(self, event):
        """Show the next or the previous picture."""
        if event[0] in (wasp.EventType.LEFT, wasp.EventType.UP):
            self._next()
        elif self._page:
            self._page -= 1
            self._draw()
        else:
            return True

    def _next(self):
        self._page += 1
        if self._page < len(PICTURES):
            self._draw()
        else:
            wasp.system.navigate(wasp.EventType.HOME)

    def _draw(self):
        """Draw the current picture, centred."""
        image = PICTURES[self._page]
        if image[0] * image[2] < 240 or image[1] * image[2] < 240:
            # Extend the picture with the colour of its top left pixel
            wasp.watch.drawable.fill(image[4] << 8 | image[5])
        self._blit(image)

    @micropython.native
    def _blit(self, image):
        """Decode and draw a 4-bit RLE image (see tools/rle4_encode.py)."""
        display = wasp.watch.display
        quick_write = display.quick_write
        w = image[0]
        h = image[1]
        scale = image[2]
        n = image[3]
        palette = array.array('H', (image[4 + 2*i] << 8 | image[5 + 2*i]
                                    for i in range(n)))

        display.set_window((240 - w*scale) // 2, (240 - h*scale) // 2,
                           w * scale, h * scale)
        buf = display.linebuffer[0:2 * w * scale]
        bp = 0
        rl = 0
        px = 0

        display.quick_start()
        for op in memoryview(image)[4 + 2*n:]:
            if rl < 0:
                rl = 16 + op
            else:
                px = palette[op >> 4]
                rl = (op & 15) + 1
                if rl == 16:
                    rl = -1
                    continue

            while rl:
                count = min(w - bp, rl)
                _fill(buf, px, count * scale, bp * scale)
                bp += count
                rl -= count

                if bp >= w:
                    for i in range(scale):
                        quick_write(buf)
                    bp = 0
        display.quick_end()

